/* dds3 kernel: the cooperative process list every subsystem runs on.
 * See include/README.md for how the layout was verified. */

#include "common.h"

typedef struct dds3ProcessID_t dds3ProcessID_t;

/* A process step returns the next step to run, 0 to stay on this one, or -1 to
 * finish. RunProcess stores a non-zero return back into processfunc. */
typedef s32 (*dds3ProcessFunc_t)(dds3ProcessID_t *id);

struct dds3ProcessID_t
{
    char name[24];
    u32 namehash; /* sum of name's bytes */
    u32 flag;     /* low nibble is the state: 1 new, 2 running, 3 ending */
    u32 priority;
    u32 starttime;
    u32 runtime;
    s16 starttimer;
    s16 shutdowntimer;
    dds3ProcessFunc_t processfunc;
    dds3ProcessFunc_t shutdownfunc;
    void *workdata;
    dds3ProcessID_t *next;
    dds3ProcessID_t *prev;
    dds3ProcessID_t *parent;
    dds3ProcessID_t *child;
    dds3ProcessID_t *sibling;
};

