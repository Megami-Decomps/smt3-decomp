"""Repair an explicitly bounded data-only Objdiff reference, never a linker input.

Splat's word-oriented data reader drops the final 1–3 bytes. Keep its
already-correct symbolic prefix, but recover the final byte cells from the
pinned retail ELF. Only named primaries in the opt-in ledger are eligible.
"""
from __future__ import annotations

import hashlib
import io
import json
from pathlib import Path
import re
import sys

import yaml
from spimdisasm.common import RelocType

from elftools.elf.elffile import ELFFile

if __package__:
    from .check_unit import native_object_offset, owned_rom_range, writable_file_data_section
    from .retail_elf import load_segments
else:
    from check_unit import native_object_offset, owned_rom_range, writable_file_data_section
    from retail_elf import load_segments

IDENT = r"[A-Za-z_][A-Za-z0-9_.$]*"
NUM = r"(?:0x[0-9a-fA-F]+|[0-9]+)"
SYMBOL = re.compile(rf"^({IDENT})\s*=\s*(\S+);$")
DATA = re.compile(
    r"^\s*/\* ([0-9A-Fa-f]+) ([0-9A-Fa-f]+)(?: ([0-9A-Fa-f]+))? \*/"
    r"\s+\.(byte|short|word)\s+(.+?)\s*$"
)
HEADER = ('.include "macro.inc"', '.section .data, "wa"',
          '/* Generated by spimdisasm 1.40.2 */')
INCBIN = re.compile(r'\.incbin "([^"\n]+)"')


def opt_ins(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}

    def unique(items):
        result = {}
        for key, val in items:
            if key in result:
                raise ValueError(f"duplicate native data tail unit: {key}")
            result[key] = val
        return result

    result = json.loads(path.read_text(), object_pairs_hook=unique)
    if not isinstance(result, dict) or not result:
        raise ValueError("native data tail ledger must name at least one explicit primary")
    for u, name in result.items():
        if (not re.fullmatch(r"[A-Za-z0-9_]+(?:/[A-Za-z0-9_]+)+", u)
                or not isinstance(name, str) or not re.fullmatch(IDENT, name)):
            raise ValueError("invalid native data tail unit or primary")
    if len(set(result.values())) != len(result):
        raise ValueError("same primary assigned to multiple native tail units")
    return result


def name_records(text: str) -> dict[str, tuple[int, int | None]]:
    out = {}
    for line in text.splitlines():
        record, _, comment = line.partition("//")
        record = record.strip()
        if not record:
            continue
        match = SYMBOL.fullmatch(record)
        if match is None or line.count(";") != 1:
            raise ValueError("unsupported native symbol record")
        name, address = match.groups()
        sizes = [x.partition(":")[2] for x in comment.split(" ") if x.startswith("size:")]
        if name in out or len(sizes) > 1:
            raise ValueError(f"duplicate native symbol or size: {name}")
        address = int(address, 0)
        size = int(sizes[0], 0) if sizes else None
        if address < 0 or size is not None and size < 0:
            raise ValueError("invalid native symbol address or size")
        out[name] = (address, size)
    return out


def check_primary(records, name, address, size):
    if records.get(name) != (address, size):
        raise ValueError("native tail primary must explicitly name the entire .data span")
    for other, (base, extent) in records.items():
        if other != name and (address <= base < address + size
                              or extent and base < address < base + extent):
            raise ValueError(f"overlapping or interior native tail symbol: {other}")


def verify_word(operand: str, width: int, names: dict[str, tuple[int, int | None]]) -> bytes:
    if re.fullmatch(rf"-?{NUM}", operand):
        value = int(operand, 0)
        if value < -(1 << (width * 8 - 1)) or value >= (1 << (width * 8)):
            raise ValueError("literal overflows its native directive")
        return (value % (1 << (width * 8))).to_bytes(width, "little")
    m = re.fullmatch(rf"({IDENT})(?:\s*([+-])\s*({NUM}))?", operand)
    if width != 4 or not m or m[1] not in names:
        raise ValueError("unsupported or unresolved native prefix relocation")
    base = names[m[1]][0]
    addend = int(m[3], 0) if m[3] is not None else 0
    value = base - addend if m[2] == "-" else base + addend
    if not 0 <= value < (1 << 32):
        raise ValueError("native prefix relocation overflow")
    return value.to_bytes(4, "little")


def complete_reference(assembly, name, payload, file_offset, address, names):
    """Verify and keep the generated prefix exactly, emit missing source bytes."""
    lines = assembly.splitlines(keepends=True)
    records = [(i, line.strip()) for i, line in enumerate(lines) if line.strip()]
    if tuple(t for _, t in records[:3]) != HEADER:
        raise ValueError("unexpected generated writable data header")
    prefix_length = len(payload) & ~3
    body = records[3:]
    if not prefix_length and not body:
        # Splat generated no symbol because its word list was empty.
        lines += [f"\nnonmatching {name}\n\ndlabel {name}\n", f"enddlabel {name}\n"]
        insert = len(lines) - 1
    else:
        if (len(body) < 3 or body[0][1] != f"nonmatching {name}"
                or body[1][1] != f"dlabel {name}" or body[-1][1] != f"enddlabel {name}"):
            raise ValueError("expected one unambiguous generated .data primary")
        at = 0
        for _, line in body[2:-1]:
            m = DATA.fullmatch(line)
            if not m:
                raise ValueError("unrecognized generated native prefix directive")
            rom, vram, native, kind, val = m.groups()
            width = {"byte": 1, "short": 2, "word": 4}[kind]
            if (int(rom, 16), int(vram, 16)) != (file_offset + at, address + at):
                raise ValueError("noncontiguous generated native prefix")
            if at + width > prefix_length:
                raise ValueError("generated prefix extends into the accounted-for tail")
            word = payload[at:at + width]
            if (native is not None and bytes.fromhex(native) != word
                    or verify_word(val, width, names) != word):
                raise ValueError("generated native prefix bytes or addend disagree with retail")
            at += width
        if at != prefix_length:
            raise ValueError("generated native prefix does not cover complete words")
        insert = body[-1][0]
    extension = [f"    /* {file_offset+i:06X} {address+i:08X} */ .byte 0x{payload[i]:02X}\n"
                 for i in range(prefix_length, len(payload))]
    if not extension:
        # An aligned control is untouched.
        return assembly
    return "".join(lines[:insert] + extension + lines[insert:])


def yaml_inputs(root, version, serial):
    conf = root / "config" / version / f"{serial}.yaml"
    plan = yaml.safe_load(conf.read_text())
    options = plan["options"]
    base = (conf.parent / options["base_path"]).resolve()
    if base != root.resolve():
        raise ValueError("unexpected Splat base_path for native data tails")
    ledger = options.get("reloc_addrs_path")
    if isinstance(ledger, str):
        ledger = [ledger]
    if not isinstance(ledger, list) or not ledger:
        raise ValueError("expected explicit Splat relocation metadata paths")
    paths = []
    for n in ledger:
        if not isinstance(n, str) or not re.fullmatch(r"[A-Za-z0-9_./-]+", n):
            raise ValueError("unsupported native relocation metadata path")
        p = (base / n).resolve()
        if not p.is_relative_to(base) or not p.is_file() or p in paths:
            raise ValueError("missing, duplicated or external relocation metadata")
        paths.append(p)
    symbols = options.get("symbol_addrs_path")
    if symbols != [f"config/{version}/symbol_addrs.txt"]:
        raise ValueError("unsupported Splat symbol metadata path list for native tails")
    return conf, plan, paths


def verify_reloc_overrides(sources, start, end):
    """Splat reloc field order/base, but refuse unknown, duplicate or ambiguous fields."""
    seen = set()
    for text in sources:
        for line in text.splitlines():
            record = line.split("//", 1)[0].strip()
            if not record:
                continue
            fields = {}
            for token in record.split(" "):
                if not token:
                    continue
                if token.count(":") != 1 or re.search(r"\s", token):
                    raise ValueError("unsupported native relocation override record")
                k, v = token.split(":")
                if k not in {"rom", "reloc", "symbol", "addend"} or k in fields or not v:
                    raise ValueError("unsupported or duplicate native relocation field")
                fields[k] = v
            if not {"rom", "reloc", "symbol"} <= fields.keys():
                raise ValueError("missing native relocation override field")
            offset = int(fields["rom"], 0)
            if "addend" in fields:
                int(fields["addend"], 0)
            if offset < 0 or offset in seen or RelocType.fromStr(fields["reloc"]) is None:
                raise ValueError("invalid or duplicate native relocation override")
            seen.add(offset)
            # Treat an override as a four-byte word; refuse any overlap.
            if offset < end and start < offset + 4:
                raise ValueError("native data owner intersects explicit relocation override")


def pad_assets(root, version, serial, selected):
    """Track real incbins only for databin siblings of explicit tail owners."""
    conf, plan, _ = yaml_inputs(root, version, serial)
    expected_assets = (root / f"assets/{version}").resolve()
    if (root / plan["options"]["asset_path"]).resolve() != expected_assets:
        raise ValueError("unexpected Splat asset path for native tail pads")
    deps = {}
    found = set()
    for segment in plan["segments"]:
        if not isinstance(segment, dict):
            continue
        rows = segment.get("subsegments", [])
        for i, row in enumerate(rows):
            if not isinstance(row, list) or len(row) != 3 or row[1] != ".data" or row[2] not in selected:
                continue
            unit = row[2]
            if unit in found:
                raise ValueError("ambiguous native tail .data owner")
            found.add(unit)
            if i == len(rows) - 1:
                raise ValueError("unbounded native tail owner")
            nxt = rows[i + 1]
            if not isinstance(nxt, list) or len(nxt) != 3 or nxt[1] != "databin":
                continue
            start, end = owned_rom_range(conf.read_text(), unit, ".data") or (None, None)
            if start != row[0] or end != nxt[0]:
                raise ValueError("native tail databin is not its actual adjacent sibling")
            name = nxt[2]
            if not isinstance(name, str) or not re.fullmatch(r"[A-Za-z0-9_]+", name):
                raise ValueError("unsupported native tail databin name")
            src = Path(f"asm/{version}/data/{name}.s")
            asset = Path(f"assets/{version}/{name}.databin.bin")
            lines = [line.strip() for line in (root / src).read_text().splitlines() if line.strip()]
            label = f"__{name}_databin"
            if (len(lines) != 6
                    or lines[:4] != [HEADER[0], HEADER[1], f"nonmatching {label}", f"dlabel {label}"]
                    or lines[5] != f"enddlabel {label}"):
                raise ValueError("expected one complete stock raw pad incbin listing")
            incbin = INCBIN.fullmatch(lines[4])
            if (not incbin or (root / incbin[1]).resolve() != (root / asset).resolve()
                    or not (root / asset).is_file()):
                raise ValueError("native tail pad incbin does not name its real extracted asset")
            if src in deps:
                raise ValueError("same raw pad attached to multiple native tail owners")
            deps[src] = asset
    if found != set(selected):
        raise ValueError("native tail opt-in missing a bounded .data owner")
    return deps


def exact_span(root, version, unit, name):
    cfg = root / "config" / version
    version_info = json.loads((root / "config/versions.json").read_text())[version]
    serial = version_info["serial"]
    conf, _, all_relocations = yaml_inputs(root, version, serial)
    rng = owned_rom_range(conf.read_text(), unit, ".data")
    if rng is None:
        raise ValueError("native tail requires one exact .data-owned YAML span")
    start, end = rng
    size = end - start
    retail = (root / "orig" / version / serial).read_bytes()
    if len(retail) != version_info["elf_size"] or hashlib.sha1(retail).hexdigest() != version_info["elf_sha1"]:
        raise ValueError("native tail requires pinned original retail ELF")
    elf = ELFFile(io.BytesIO(retail))
    if elf.elfclass != 32 or not elf.little_endian or elf["e_type"] != "ET_EXEC":
        raise ValueError("not the supported file-backed retail ELF")
    r = writable_file_data_section(elf, len(retail))
    if r is None:
        raise ValueError("native .data is not unique writable PROGBITS")
    index, data = r
    off = data["sh_offset"]
    addr = data["sh_addr"] + start - off
    if not off <= start < end <= off + data["sh_size"] or native_object_offset(load_segments(retail), addr, size, len(retail)) != start:
        raise ValueError("native tail outside unique .data/PT_LOAD mapping")
    if any(s["sh_type"] in ("SHT_REL", "SHT_RELA") and s["sh_info"] == index and s["sh_size"]
           for s in elf.iter_sections()):
        raise ValueError("native data tail does not support file relocation sections")
    verify_reloc_overrides((p.read_text() for p in all_relocations), start, end)
    names = name_records((cfg / "symbol_addrs.txt").read_text())
    check_primary(names, name, addr, size)
    return start, addr, retail[start:end], names


def main(version, unit, input_path, output_path):
    root = Path(__file__).resolve().parent.parent
    ledger = root / "config" / version / "native_data_tails.json"
    name = opt_ins(ledger).get(unit)
    if name is None:
        raise ValueError("missing explicit native data tail opt-in")
    normal_ref = root / "asm" / version / "data" / (unit + ".data.s")
    if Path(input_path).resolve() != normal_ref.resolve():
        raise ValueError("native tail input is not this owner's stock generated reference")
    file_offset, address, payload, symbols = exact_span(root, version, unit, name)
    if not len(payload) % 4:
        raise ValueError("word-aligned owner does not need native data tail recovery")
    result = complete_reference(normal_ref.read_text(), name, payload, file_offset, address, symbols)
    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_suffix(out.suffix + ".tmp")
    tmp.write_text(result)
    tmp.replace(out)


if __name__ == "__main__":
    try:
        main(*sys.argv[1:])
    except (OSError, ValueError) as exc:
        sys.exit(str(exc))
