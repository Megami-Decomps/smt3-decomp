#!/usr/bin/env python3
"""Export IDB struct members to config/smt3/ida_members.txt.

Unlike the HD corpus, these offsets and sizes are usable: the IDB's layouts are
applied at real PS2 addresses, and sdfMatPacket_t is 0xa0 here as in this project's
proven assertions where HD says 0x78. Read-only on the IDB side."""

import argparse
import base64
import json
import os
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "config" / "smt3" / "ida_members.txt"
DEFAULT_INSTANCE = "SLUS_209.11"
IDA_SCRIPTS = Path(
    os.environ.get("IDA_SKILL_SCRIPTS", Path.home() / ".claude/skills/ida-instances/scripts")
)

HEADER = "# generated by tools/ida_members.py; do not edit"
NAME_OK = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

IDA_PAYLOAD = r'''
def export():
    import base64, json, zlib
    import ida_typeinf

    til = ida_typeinf.get_idati()
    rows = []
    for ordinal in range(1, ida_typeinf.get_ordinal_limit(til)):
        name = ida_typeinf.get_numbered_type_name(til, ordinal)
        if not name:
            continue
        info = ida_typeinf.tinfo_t()
        if not info.get_numbered_type(til, ordinal):
            continue
        if not (info.is_struct() or info.is_union()):
            continue
        udt = ida_typeinf.udt_type_data_t()
        if not info.get_udt_details(udt):
            continue
        size = info.get_size()
        if size is None or size > 0xFFFFFF:
            continue
        members = []
        for member in udt:
            # IDA reports a member's place and extent in bits.
            members.append([
                member.name,
                member.offset // 8,
                member.size // 8,
                str(member.type),
            ])
        rows.append([name, "union" if info.is_union() else "struct", size, members])
    blob = json.dumps(rows, separators=(",", ":")).encode()
    return base64.b64encode(zlib.compress(blob, 9)).decode()


MEMBER_BLOB = export()
len(MEMBER_BLOB)
'''

PAGE = 16384


def eval_in_ida(ida, port, code, new_locals):
    out = ida.call_tool(port, "py_eval", {"code": code, "new_locals": new_locals})
    if out.get("stderr"):
        raise SystemExit(f"IDAPython failed:\n{out['stderr']}")
    return out.get("result")


def collect(instance, ports):
    sys.path.insert(0, str(IDA_SCRIPTS))
    import ida

    instances = ida.get_instances(ida.parse_ports(ports), refresh=False)
    port = ida.resolve_target(instance, instances)
    total = int(eval_in_ida(ida, port, IDA_PAYLOAD, True))
    pages = []
    for start in range(0, total, PAGE):
        page = eval_in_ida(ida, port, f"MEMBER_BLOB[{start}:{start + PAGE}]", False)
        if len(page) != min(PAGE, total - start):
            raise SystemExit(f"short page at {start}: got {len(page)} characters")
        pages.append(page)
    return port, json.loads(zlib.decompress(base64.b64decode("".join(pages))))


def render(rows):
    lines = [
        HEADER,
        "# T <name> <kind> <size>   then one M row per member:",
        "# M <offset> <size> <type> <name>",
    ]
    for name, kind, size, members in rows:
        lines.append(f"T {name} {kind} {size}")
        for mname, offset, msize, mtype in members:
            lines.append(f"M {offset} {msize} {mtype.replace(' ', '')} {mname}")
    return "\n".join(lines) + "\n"


def load(path):
    """{name: (kind, size, [(offset, size, type, member)])}."""
    out, cur = {}, None
    path = Path(path)
    if not path.exists():
        return out
    for line in path.read_text().splitlines():
        if line.startswith("T "):
            parts = line.split()
            cur = parts[1]
            out[cur] = (parts[2], int(parts[3]), [])
        elif line.startswith("M ") and cur:
            parts = line.split(None, 4)
            out[cur][2].append((int(parts[1]), int(parts[2]), parts[3],
                                parts[4] if len(parts) > 4 else ""))
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--instance", default=DEFAULT_INSTANCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--ports", default=os.environ.get("IDA_MCP_PORTS", "13337-13437"))
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    port, payload = collect(args.instance, args.ports)
    kept = sorted((row for row in payload if NAME_OK.match(row[0])), key=lambda row: row[0])
    named = sum(1 for _, _, _, ms in kept for m, _, _, _ in ms if m)
    total = sum(len(ms) for _, _, _, ms in kept)
    print(f"instance {port}: {len(kept)} types, {total} members, {named} of them named")
    if args.dry_run:
        return
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(kept))
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
