#!/usr/bin/env python3
"""Export symbol names from the SLUS_209.11 IDB into splat's symbol_addrs format.

Runs IDAPython in the open IDA instance over the ida-instances MCP transport and
writes config/smt3/symbol_addrs.txt. Read-only on the IDB side.
"""

import argparse
import base64
import json
import os
import re
import sys
import zlib
from collections import namedtuple
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "config" / "smt3" / "symbol_addrs.txt"
# Address the database by module name: the port it answers on moves between sessions.
DEFAULT_INSTANCE = "SLUS_209.11"
IDA_SCRIPTS = Path(
    os.environ.get("IDA_SKILL_SCRIPTS", Path.home() / ".claude/skills/ida-instances/scripts")
)

BEGIN = "// BEGIN ida (generated by tools/ida_symbols.py; edit outside this block)"
END = "// END ida"

# SLUS_209.11 section table, from the ELF section headers. Only sections that can
# hold a symbol; the IDB also maps the EE hardware registers, which are not in the ELF.
SECTIONS = [
    (".text", 0x00100000, 0x1E6E44),
    (".vutext", 0x002E6E50, 0x00E7B0),
    (".ctors", 0x002F5600, 0x000008),
    (".dtors", 0x002F5608, 0x000008),
    (".data", 0x002F5680, 0x2382BC),
    (".eh_frame", 0x0052D940, 0x000004),
    (".vudata", 0x0052D944, 0x000300),
    (".rodata", 0x0052DC80, 0x01E4F8),
    (".lit4", 0x0054C180, 0x002654),
    (".sdata", 0x0054E800, 0x003355),
    (".sbss", 0x00551B80, 0x0005FC),
    (".bss", 0x00552180, 0x04E1B0),
]
SECTION_ORDER = [name for name, _, _ in SECTIONS]

Symbol = namedtuple("Symbol", "addr name type size")
NAME_OK = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

IDA_PAYLOAD = r'''
def export():
    # py_eval execs this with split globals and locals, so the imports have to live
    # inside the function for its body to see them.
    import base64, json, re, zlib
    import ida_bytes, ida_funcs, ida_segment, idautils, idc

    # IDA placeholder names plus the names splat and spimdisasm generate themselves.
    PLACEHOLDER = re.compile(
        r"^(sub|nullsub|func|loc|locret|def|unk|byte|word|dword|qword|oword|tbyte"
        r"|flt|dbl|asc|stru|algn|jpt|jtbl|off|seg|j_sub|SEH|unknown_libname"
        r"|D|L|B|RO|STR|jlbl)_[0-9A-Fa-f]+$"
    )
    # The IDB maps the EE registers (EE_GS, EE_VIF, ...) above this; they are not in the ELF.
    HARDWARE_BASE = 0x10000000

    # splat types attested in the reference repo's symbol_addrs.txt. Anything else is
    # emitted with a size only, so a type spimdisasm may not know never reaches the file.
    ELEMENT_TYPES = (
        ("is_strlit", "asciz"),
        ("is_byte", "u8"),
        ("is_word", "u16"),
        ("is_dword", "u32"),
    )

    def segment_of(ea):
        seg = ida_segment.getseg(ea)
        return ida_segment.get_segm_name(seg) if seg else None

    def data_type(flags):
        for probe, name in ELEMENT_TYPES:
            if getattr(ida_bytes, probe)(flags):
                return name
        return None

    rows = []
    skipped = []
    # Every function in the IDB is in .text; .vutext holds VU microcode, which reaches
    # the file as plain data symbols with a size and no type.
    funcs = set(idautils.Functions())

    for ea in sorted(funcs):
        name = idc.get_func_name(ea)
        if PLACEHOLDER.match(name):
            continue
        func = ida_funcs.get_func(ea)
        chunks = len(list(idautils.Chunks(ea)))
        # A size pins the function's extent in spimdisasm, so only trust contiguous functions.
        size = func.end_ea - ea if chunks == 1 else None
        rows.append([ea, name, "func", size])

    for ea, name in idautils.Names():
        if ea in funcs:
            continue
        seg = segment_of(ea)
        if seg is None or ea >= HARDWARE_BASE:
            skipped.append([ea, name, "outside the ELF"])
            continue
        flags = ida_bytes.get_flags(ea)
        if not ida_bytes.has_user_name(flags):
            # IDA invented this one (aFooBar string names and the like); splat names it itself.
            continue
        if PLACEHOLDER.match(name):
            continue
        if ida_bytes.is_code(flags):
            if ida_funcs.get_func(ea):
                skipped.append([ea, name, "label inside a function"])
                continue
            rows.append([ea, name, "func", None])
            continue
        size = None if ida_bytes.is_unknown(flags) else ida_bytes.get_item_size(ea)
        kind = data_type(flags)
        if kind == "asciz":
            # spimdisasm takes a string's extent from its terminator and warns when a
            # declared size disagrees; a 2 or 3 byte "string" is a mistyped scalar.
            kind, size = (None, size) if size is not None and size < 4 else ("asciz", None)
        rows.append([ea, name, kind, size])

    blob = json.dumps({"rows": rows, "skipped": skipped}, separators=(",", ":"))
    return base64.b64encode(zlib.compress(blob.encode(), 9)).decode()


SYMBOL_BLOB = export()
len(SYMBOL_BLOB)
'''


# The MCP transport truncates a reply above roughly 20 KB, so the blob is read in pages.
PAGE = 16384


def eval_in_ida(ida, port, code, new_locals):
    out = ida.call_tool(port, "py_eval", {"code": code, "new_locals": new_locals})
    if out.get("stderr"):
        raise SystemExit(f"IDAPython failed:\n{out['stderr']}")
    return out.get("result")


def collect(instance, ports):
    sys.path.insert(0, str(IDA_SCRIPTS))
    import ida

    instances = ida.get_instances(ida.parse_ports(ports), refresh=False)
    port = ida.resolve_target(instance, instances)
    total = int(eval_in_ida(ida, port, IDA_PAYLOAD, True))
    pages = []
    for start in range(0, total, PAGE):
        page = eval_in_ida(ida, port, f"SYMBOL_BLOB[{start}:{start + PAGE}]", False)
        if len(page) != min(PAGE, total - start):
            raise SystemExit(f"short page at {start}: got {len(page)} characters")
        pages.append(page)
    return port, json.loads(zlib.decompress(base64.b64decode("".join(pages))))


def section_of(addr):
    for name, start, size in SECTIONS:
        if start <= addr < start + size:
            return name
    return None


def format_line(row):
    attrs = []
    if row.type:
        attrs.append(f"type:{row.type}")
    if row.size:
        attrs.append(f"size:0x{row.size:X}")
    suffix = f" // {' '.join(attrs)}" if attrs else ""
    return f"{row.name} = 0x{row.addr:08X};{suffix}"


def render(rows):
    by_section = {}
    for row in rows:
        by_section.setdefault(section_of(row.addr), []).append(row)
    lines = [BEGIN]
    for section in SECTION_ORDER:
        group = by_section.get(section)
        if not group:
            continue
        kinds = "functions" if all(r.type == "func" for r in group) else "data"
        lines.append(f"// {section} {kinds} ({len(group)})")
        lines.extend(format_line(row) for row in group)
    lines.append(END)
    return lines


def splice(path, block):
    """Replace the generated block, keeping hand-curated lines around it."""
    head = [
        "// Symbols seeded from the SLUS_209.11 IDB by tools/ida_symbols.py.",
        "// Hand-curated symbols go above the generated block and win over it.",
    ]
    tail = []
    if path.exists():
        old = path.read_text().splitlines()
        if BEGIN in old and END in old:
            head = old[: old.index(BEGIN)]
            tail = old[old.index(END) + 1 :]
    return "\n".join(head + block + tail) + "\n"


def check(rows):
    problems = []
    addrs = [row.addr for row in rows]
    if addrs != sorted(addrs):
        problems.append("addresses are not sorted")
    for addr, count in sorted(_counts(addrs).items()):
        if count > 1:
            problems.append(f"address 0x{addr:08X} appears {count} times")
    for name, count in sorted(_counts([row.name for row in rows]).items()):
        if count > 1:
            problems.append(f"name {name} appears {count} times")
    for row in rows:
        if section_of(row.addr) is None:
            problems.append(f"0x{row.addr:08X} {row.name} is outside every section")
        if row.type == "func" and row.addr % 4:
            problems.append(f"function {row.name} at 0x{row.addr:08X} is not 4-byte aligned")
        if row.type == "func" and row.size and row.size % 4:
            problems.append(f"function {row.name} has size 0x{row.size:X}")
        if not NAME_OK.match(row.name):
            problems.append(f"name {row.name} at 0x{row.addr:08X} is not a plain identifier")
    return problems


def _counts(values):
    counts = {}
    for value in values:
        counts[value] = counts.get(value, 0) + 1
    return counts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--instance", default=DEFAULT_INSTANCE, help="IDA instance (port or name)")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--ports", default=os.environ.get("IDA_MCP_PORTS", "13337-13437"))
    parser.add_argument("--dry-run", action="store_true", help="report counts, write nothing")
    args = parser.parse_args()

    port, payload = collect(args.instance, args.ports)
    rows = sorted((Symbol(*row) for row in payload["rows"]), key=lambda row: (row.addr, row.name))

    problems = check(rows)
    if problems:
        for problem in problems[:20]:
            print(f"error: {problem}", file=sys.stderr)
        raise SystemExit(f"{len(problems)} problems; fix the script, not the output")

    funcs = sum(1 for row in rows if row.type == "func")
    print(f"instance {port}: {funcs} functions, {len(rows) - funcs} data symbols")
    for reason, count in sorted(_counts([entry[2] for entry in payload["skipped"]]).items()):
        print(f"  skipped {count}: {reason}")
    if args.dry_run:
        return
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(splice(args.output, render(rows)))
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
