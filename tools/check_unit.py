                # each LO16 with the lui that loaded its base register: gcc can
                # hoist one pair's lui above another's.
                if rtype == "R_MIPS_HI16":
                    text_hi[(mine >> 16) & 0x1F] = (i, mine, want)
                    continue
                hi = text_hi.get((mine >> 21) & 0x1F)
