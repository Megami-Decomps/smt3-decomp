def linked_numeric_absolute_symbols(path, canonical):
    """Load only explicitly linked, self-consistent autogenerated absolutes.

    Short D_ labels can spell scalar constants, not just object addresses.
    Never infer their value from an unlinked name or import arbitrary providers.
    configure.py passes this exact undefined-symbol file to the final linker.
    """
    if not path.exists():
        return {}
    out = {}
    for number, line in enumerate(path.read_text().splitlines(), 1):
        name_match = re.match(r"^\s*(D_[0-9A-F]{1,8})(?=[^A-Za-z0-9_]|$)", line)
        if not name_match:
            continue
        name = name_match.group(1)
        row = re.fullmatch(r"\s*" + re.escape(name) +
                           r"\s*=\s*0x([0-9A-Fa-f]+)\s*;\s*(?://.*)?", line)
        if not row:
            raise ValueError(f"{path.name}:{number}: malformed absolute definition for {name}")
        value = int(row.group(1), 16)
        if value != int(name[2:], 16):
            raise ValueError(f"{path.name}:{number}: absolute value disagrees with numeric label {name}")
        if name in out:
            raise ValueError(f"{path.name}:{number}: duplicate absolute definition for {name}")
        if name in canonical and canonical[name] != value:
            raise ValueError(f"{path.name}:{number}: absolute definition conflicts with canonical symbol {name}")
        out[name] = value
    return out


def symbols(version):
    # Splat's linker script supplies this absolute ABI symbol, not a C/BSS object.
    out = {"_gp": int(VERSIONS[version]["gp"], 16)}
    for line in (ROOT / "config" / version / "symbol_addrs.txt").read_text().splitlines():
        if m := ROW.match(line):
            out.setdefault(m.group(1), int(m.group(2), 16))
    # Trust this standard linker input only when the selected YAML enables it.
    config = ROOT / "config" / version / f"{VERSIONS[version]['serial']}.yaml"
    if config.exists():
        config_text = config.read_text()
        if len(re.findall(r"^\s*undefined_syms_auto_path\s*:", config_text, re.M)) > 1:
            raise ValueError(f"{config.name}: ambiguous undefined_syms_auto_path")
        try:
            document = yaml.safe_load(config_text) or {}
        except yaml.YAMLError as exc:
            raise ValueError(f"{config.name}: malformed linker configuration") from exc
        options = document.get("options", {}) if isinstance(document, dict) else {}
        expected = f"config/{version}/undefined_syms_auto.txt"
        if isinstance(options, dict) and options.get("undefined_syms_auto_path") == expected:
            out.update(linked_numeric_absolute_symbols(ROOT / expected, out))
    return out


def symbol_sizes(version):
    """Read explicit native extents; an address interval may include alignment."""
    out = {}
    for line in (ROOT / "config" / version / "symbol_addrs.txt").read_text().splitlines():
        row = ROW.match(line)
        size = re.search(r"\bsize:([^\s/]+)", line)
        if row and size:
            out[row.group(1)] = int(size.group(1), 0)
    return out


def address(name, syms):
    if name in syms:
        return syms[name]
    m = AUTO.match(name)
    return int(m.group(1), 16) if m else None


def compiler_local_function_aliases(objdump_text, funcs, syms, function_names):
    """Resolve only unambiguous local STT_FUNC numeric compiler suffixes.

    Keep exact configured names authoritative. A numeric suffix alone is not
    identity evidence: the object must define one local text function with the
    same extent reported by nm, and no plain or other suffixed definition may
    compete for its canonical, explicitly typed retail function name. Use the
    complete objdump inventory for competitors: nm omits the size column for
    zero-size symbols, so they are absent from the sized-function list.
    """
    grouped = {}
    for offset, size, name in funcs:
        stem = re.sub(r"\.\d+$", "", name)
        grouped.setdefault(stem, []).append((offset, size, name))
    definitions = {}
    definition_stems = {}
    for line in objdump_text.splitlines():
        parts = line.split()
        if ".text" not in parts:
            continue
        section = parts.index(".text")
        if section == 0 or section + 2 >= len(parts):
            continue
        try:
            offset = int(parts[0], 16)
            size = int(parts[section + 1], 16)
        except ValueError:
            continue
        flags = parts[1:section]
        local_function = "l" in flags and "F" in flags and "g" not in flags
        name = parts[section + 2]
        definitions.setdefault(name, []).append((offset, size, local_function))
        stem = re.sub(r"\.\d+$", "", name)
        definition_stems.setdefault(stem, []).append(name)
    aliases = {}
    for stem, entries in grouped.items():
        if len(entries) != 1 or stem not in function_names or stem not in syms:
            continue
        offset, size, name = entries[0]
        if name in syms or not re.fullmatch(r"[A-Za-z_]\w*\.\d+", name):
            continue
        if definition_stems.get(stem) != [name]:
            continue
        if size <= 0 or definitions.get(name) != [(offset, size, True)]:
            continue
        aliases[name] = syms[stem]
    return aliases


def native_function_inventory(assembly, text_range, function_names, syms, segs):
    """Native entries plus explicit recovered inner entries in this YAML span."""
    names = set(re.findall(r"^\s*(?:glabel|alabel) (\S+)", assembly, re.M))
    start, end = text_range
    for name in function_names:
        addr = syms.get(name)
        off = va_to_off(segs, addr) if addr is not None else None
        if off is not None and start <= off < end:
            names.add(name)
    return names


def full_context_function_inventory_problems(objdump_text, native_names, aliases=None, skip_names=()):
    """Reject emitted functions outside the retail owner's entry inventory.

    Existing SKIP_ASM functions retain their normal code/address diagnostics.
    The SKIP_ASM inventory cannot see definitions conditional on the actual
    build. Only verified compiler-local aliases may supplement native names;
    an address known elsewhere in the game does not confer ownership here.
    Section markers and assembler labels are not STT_FUNC definitions.
    """
    allowed = set(native_names) | set(aliases or {}) | set(skip_names)
    problems = []
    for line in objdump_text.splitlines():
        parts = line.split()
        if len(parts) < 6 or parts[-3] != ".text" or "F" not in parts[1:-3]:
            continue
        name = parts[-1]
        if name not in allowed:
            problems.append(f"unexpected emitted function {name}: not in the retail unit's entry inventory")
    return problems


def full_context_entry_placement_problems(objdump_text, native_names, syms, origin, aliases=None):
    """Verify full-build entry addresses against the fixed YAML owner origin.

    Identical text and a valid set of names do not establish entry placement:
    moving a label alone changes calls from other owners. Include zero-sized
    assembler labels as well as C function symbols; do not infer function size.
    """
    problems = []
    for line in objdump_text.splitlines():
        parts = line.split()
        if len(parts) < 5 or parts[-3] != ".text":
            continue
        name = parts[-1]
        if name not in native_names and name not in (aliases or {}):
            continue
        expected = syms.get(name, (aliases or {}).get(name))
        if expected is None:
            expected = address(name, syms)
        try:
            offset = int(parts[0], 16)
        except ValueError:
            offset = None
        if origin is None or expected is None or offset is None:
            problems.append(f"full unit entry {name} has no verified placement")
        elif origin + offset != expected:
            problems.append(f"full unit entry {name} is at 0x{origin + offset:X}, expected 0x{expected:X}")
    return problems



def full_context_data_placement_problems(objdump_text, syms, section_bases):
    """Check known initialized-data labels, including full-only assembler labels.

    Raw section equality cannot establish exported label placement. Resolve
    native names independently of emitted offsets, and use fixed YAML origins.
    Unknown compiler-local labels do not establish new retail symbols.
    """
    problems = []
    for line in objdump_text.splitlines():
        parts = line.split()
        if len(parts) < 5 or parts[-3] not in (".rodata", ".sdata", ".data"):
            continue
        section, name = parts[-3], parts[-1]
        if name == section:
            continue
        expected = address(name, syms)
        if expected is None:
            continue
        origin = section_bases.get(section)
        try:
            offset = int(parts[0], 16)
        except ValueError:
            offset = None
        if origin is None or offset is None:
            problems.append(f"full unit data label {name} has no verified placement")
        elif origin + offset != expected:
            problems.append(f"full unit data label {name} is at 0x{origin + offset:X}, expected 0x{expected:X}")
    return problems


def full_context_text_problems(text, native, origin, relocs, syms, gp,
                               section_bases, lit4, object_gp, retail, segs):
    """Check the linked owner span, including bodies absent under SKIP_ASM.

    Function-size metadata can include padding or encompass inner entries.
    The YAML text span instead fixes every instruction's placement. Only
    zero alignment suffixes may differ in length, never nonzero omitted code.
    """
    if origin is None or len(text) % 4 or len(native) % 4:
        return ["full unit's text has no aligned native span"]
    if len(text) > len(native):
        return ["full unit's text exceeds its native owner span"]
    if any(native[len(text):]):
        return ["full unit omits nonzero bytes at the end of its native text span"]
    if any(at < 0 or at % 4 or at + 4 > len(text) for at in relocs):
        return ["full unit's text relocation is outside its aligned span"]
    want = native[:len(text)]
    # Section-relative references use the fixed owner origin, including inner
    # labels with no independent symbol size. No arbitrary function inference.
    local_syms = dict(syms, __check_unit_text_origin=origin)
    hi_addends = paired_hi16_addends(text, relocs)
    differences = full_context_relocation_diffs(
        text, 0, len(text), want, relocs,
        [(0, len(text), "__check_unit_text_origin")], local_syms, gp,
        hi_addends, section_bases, object_gp)
    differences.extend(full_context_literal_diffs(
        text, 0, len(text), want, relocs, lit4, object_gp, retail, segs, gp))
    for i in range(0, len(text), 4):
        mine_word = struct.unpack_from("<I", text, i)[0]
        want_word = struct.unpack_from("<I", want, i)[0]
        relocation = relocs.get(i)
        mask = 0xFFFFFFFF
        if relocation:
            kind, symbol = relocation
            base = symbol.split("+", 1)[0]
            supported = kind in ("R_MIPS_26", "R_MIPS_HI16", "R_MIPS_LO16", "R_MIPS_GPREL16")
            known_section = (not base.startswith(".")
                             or (base == ".text" and kind in ("R_MIPS_26", "R_MIPS_HI16", "R_MIPS_LO16"))
                             or section_bases.get(base) is not None)
            literal = kind in ("R_MIPS_LITERAL", "R_MIPS_GPREL16") and base == ".lit4"
            if (kind == "R_MIPS_HI16" and i not in hi_addends) or (not literal and not (supported and known_section)):
                differences.append((i, mine_word, want_word, f"unresolved {kind} {symbol}"))
            mask = 0xFC000000 if kind == "R_MIPS_26" else 0xFFFF0000
        if mine_word & mask != want_word & mask:
            differences.append((i, mine_word, want_word, "instruction"))
    if differences:
        first = differences[0]
        return [f"full unit's text differs from retail at +0x{first[0]:X} ({first[3]})"]
    return []


def run(*cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, text=True, **kw).stdout


def sections(obj):
    """{name: (offset, size)} for every section of an ELF32 object."""
    data = Path(obj).read_bytes()
    shoff = struct.unpack_from("<I", data, 0x20)[0]
    shnum, shstrndx = struct.unpack_from("<HH", data, 0x30)
    sh = [struct.unpack_from("<10I", data, shoff + i * 40) for i in range(shnum)]
    names = sh[shstrndx][4]
    return data, {data[names + s[0]:data.index(b"\0", names + s[0])].decode(): (s[4], s[5]) for s in sh}


def text_section(obj):
    data, secs = sections(obj)
    off, size = secs.get(".text", (0, 0))
    return data[off:off + size]


# Only units with their own .rodata subsegment (tools/split_rodata.py) may emit
# rodata; jump tables are checked entry by entry and literals against native
# bytes. Initialized .data additionally requires an explicit bounded YAML owner
# and exact object/byte/relocation checks. A unit may emit zero-initialized data
# only when the YAML gives the matching section an exact, bounded dict-form
# subsegment; all other data remains fail-closed.
DATA_SECTIONS = (".rodata", ".data", ".sdata", ".sbss", ".bss", ".lit4", ".lit8")
YAML_ITEM = re.compile(
    r"^(?P<indent>[ \t]*)-\s*(?P<body>[^\n#]*?)(?:\s+#.*)?$", re.M
)


def _inline_yaml_fields(body):
    """Parse the scalar fields from one simple inline YAML mapping."""
    body = body.strip()
    if not body.startswith("{") or not body.endswith("}"):
        return None
    fields = {}
    for field in body[1:-1].split(","):
        if ":" not in field:
            return None
        key, value = field.split(":", 1)
        fields[key.strip()] = value.strip().strip("'\"")
    return fields


def owned_nobits_range(yaml_text, unit, section):
    """Return an exact per-unit NOBITS ``(vram, size)``, or None.

    NOBITS subsegments share a file offset, so their retail size comes from
    consecutive VRAM boundaries.  Accept only an unambiguous inline mapping
    whose immediate sibling is another inline mapping with a greater VRAM.
    """
    if section not in (".sbss", ".bss"):
        raise ValueError(f"unsupported NOBITS section {section!r}")
    items = list(YAML_ITEM.finditer(yaml_text))
    matches = []
    for index, item in enumerate(items):
        fields = _inline_yaml_fields(item.group("body"))
        if fields is None or fields.get("type") != section \
                or fields.get("name") != unit:
            continue
        try:
            start = int(fields["vram"], 0)
        except (KeyError, ValueError):
            continue
        sibling = None
        indent = len(item.group("indent"))
        for later in items[index + 1:]:
            later_indent = len(later.group("indent"))
            if later_indent < indent:
                break
            if later_indent == indent:
                sibling = later
                break
        if sibling is None:
            continue
        next_fields = _inline_yaml_fields(sibling.group("body"))
        try:
            end = int(next_fields["vram"], 0) if next_fields is not None else 0
        except (KeyError, ValueError):
            continue
        if end > start:
            matches.append((start, end - start))
    return matches[0] if len(matches) == 1 else None


