#!/usr/bin/env python3
"""Export the game's il2cpp struct members from the SMT3HD PC build's database.

The reconstruction's headers declare 1042 records, only what its sources needed.
The remaster's own metadata carries every class, so `<Name>__Fields` in the
GameAssembly.dll database gives member names and order for records the headers
leave out. Offsets there are the 64-bit managed layout, advisory only; the names
and their order are what this is for. Read-only on the IDB side."""

import argparse
import base64
import json
import os
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "config" / "smt3" / "hd_il2cpp_types.txt"
DEFAULT_INSTANCE = "GameAssembly.dll"
IDA_SCRIPTS = Path(
    os.environ.get("IDA_SKILL_SCRIPTS", Path.home() / ".claude/skills/ida-instances/scripts")
)
HEADER = "# generated by tools/hd_il2cpp_types.py; do not edit"
# The managed runtime's own types, and Unity's, are not this game's records.
FOREIGN = re.compile(r"^(?:System|UnityEngine|Unity|Il2Cpp|Microsoft|Mono|TMPro|DG_|"
                     r"Spine|Cinemachine|UnityEditor|Newtonsoft|_|method_|struct_)")
NAME_OK = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

IDA_PAYLOAD = r'''
def export():
    import base64, json, zlib
    import ida_typeinf

    til = ida_typeinf.get_idati()
    rows = []
    for ordinal in range(1, ida_typeinf.get_ordinal_limit(til)):
        name = ida_typeinf.get_numbered_type_name(til, ordinal)
        if not name or not name.endswith("__Fields"):
            continue
        info = ida_typeinf.tinfo_t()
        if not info.get_numbered_type(til, ordinal) or not info.is_struct():
            continue
        udt = ida_typeinf.udt_type_data_t()
        if not info.get_udt_details(udt):
            continue
        size = info.get_size()
        if size is None or size > 0xFFFFFF:
            continue
        members = [[m.name, m.offset // 8, m.size // 8, str(m.type)] for m in udt]
        if members:
            rows.append([name[:-len("__Fields")], "struct", size, members])
    blob = json.dumps(rows, separators=(",", ":")).encode()
    return base64.b64encode(zlib.compress(blob, 9)).decode()


MEMBER_BLOB = export()
len(MEMBER_BLOB)
'''

PAGE = 16384


def eval_in_ida(ida, port, code, new_locals):
    out = ida.call_tool(port, "py_eval", {"code": code, "new_locals": new_locals})
    if out.get("stderr"):
        raise SystemExit(f"IDAPython failed:\n{out['stderr']}")
    return out.get("result")


def collect(instance, ports):
    sys.path.insert(0, str(IDA_SCRIPTS))
    import ida

    instances = ida.get_instances(ida.parse_ports(ports), refresh=False)
    port = ida.resolve_target(instance, instances)
    total = int(eval_in_ida(ida, port, IDA_PAYLOAD, True))
    pages = []
    for start in range(0, total, PAGE):
        page = eval_in_ida(ida, port, f"MEMBER_BLOB[{start}:{start + PAGE}]", False)
        if len(page) != min(PAGE, total - start):
            raise SystemExit(f"short page at {start}: got {len(page)} characters")
        pages.append(page)
    return port, json.loads(zlib.decompress(base64.b64decode("".join(pages))))


def render(rows):
    lines = [HEADER,
             "# T <name> struct <size>   then one M row per member:",
             "# M <offset> <size> <type> <name>",
             "# Offsets and sizes are the remaster's 64-bit layout, not the PS2's."]
    for name, kind, size, members in rows:
        lines.append(f"T {name} {kind} {size}")
        for mname, offset, msize, mtype in members:
            lines.append(f"M {offset} {msize} {mtype.replace(' ', '')} {mname}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--instance", default=DEFAULT_INSTANCE)
    ap.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    ap.add_argument("--ports", default=os.environ.get("IDA_MCP_PORTS", "13337-13437"))
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    port, payload = collect(args.instance, args.ports)
    kept = sorted((r for r in payload if NAME_OK.match(r[0]) and not FOREIGN.match(r[0])),
                  key=lambda r: r[0])
    named = sum(1 for _, _, _, ms in kept for m, _, _, _ in ms if m)
    print(f"port {port}: {len(payload)} il2cpp records, {len(kept)} of this game's, "
          f"{named} named members")
    if not args.dry_run:
        args.output.write_text(render(kept))
        print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
