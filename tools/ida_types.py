#!/usr/bin/env python3
"""Export named types from the SLUS_209.11 IDB to config/smt3/ida_types.txt.

One line per type, `name kind size`. tools/check_names.py reads that file so the
naming check runs without IDA open. Read-only on the IDB side.
"""

import argparse
import base64
import json
import os
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "config" / "smt3" / "ida_types.txt"
# Address the database by module name: the port it answers on moves between sessions.
DEFAULT_INSTANCE = "SLUS_209.11"
IDA_SCRIPTS = Path(
    os.environ.get("IDA_SKILL_SCRIPTS", Path.home() / ".claude/skills/ida-instances/scripts")
)

HEADER = "# generated by tools/ida_types.py; do not edit"

# IDA spells an unnamed type as a hash, and a C++ template instantiation leaks in
# from the HD symbol import. Neither is a name the tree could adopt.
NAME_OK = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

IDA_PAYLOAD = r'''
def export():
    # py_eval execs this with split globals and locals, so the imports have to live
    # inside the function for its body to see them.
    import base64, json, zlib
    import ida_typeinf

    til = ida_typeinf.get_idati()
    rows = []
    for ordinal in range(1, ida_typeinf.get_ordinal_limit(til)):
        name = ida_typeinf.get_numbered_type_name(til, ordinal)
        if not name:
            continue
        info = ida_typeinf.tinfo_t()
        if not info.get_numbered_type(til, ordinal):
            continue
        if info.is_enum():
            kind = "enum"
        elif info.is_union():
            kind = "union"
        elif info.is_struct():
            kind = "struct"
        elif info.is_typeref() or info.is_typedef():
            kind = "typedef"
        elif info.is_func() or info.is_funcptr():
            kind = "func"
        else:
            kind = "other"
        size = info.get_size()
        # An incomplete type reports the all-ones sentinel rather than a size.
        rows.append([name, kind, -1 if size is None or size > 0xFFFFFF else size])
    blob = json.dumps(rows, separators=(",", ":")).encode()
    return base64.b64encode(zlib.compress(blob, 9)).decode()


TYPE_BLOB = export()
len(TYPE_BLOB)
'''

# The MCP transport truncates a reply above roughly 20 KB, so the blob is read in pages.
PAGE = 16384


def eval_in_ida(ida, port, code, new_locals):
    out = ida.call_tool(port, "py_eval", {"code": code, "new_locals": new_locals})
    if out.get("stderr"):
        raise SystemExit(f"IDAPython failed:\n{out['stderr']}")
    return out.get("result")


def collect(instance, ports):
    sys.path.insert(0, str(IDA_SCRIPTS))
    import ida

    instances = ida.get_instances(ida.parse_ports(ports), refresh=False)
    port = ida.resolve_target(instance, instances)
    total = int(eval_in_ida(ida, port, IDA_PAYLOAD, True))
    pages = []
    for start in range(0, total, PAGE):
        page = eval_in_ida(ida, port, f"TYPE_BLOB[{start}:{start + PAGE}]", False)
        if len(page) != min(PAGE, total - start):
            raise SystemExit(f"short page at {start}: got {len(page)} characters")
        pages.append(page)
    return port, json.loads(zlib.decompress(base64.b64decode("".join(pages))))


def render(rows):
    lines = [HEADER]
    for name, kind, size in rows:
        lines.append(f"{name} {kind} {size}")
    return "\n".join(lines) + "\n"


def load(path):
    """Parse an ida_types.txt into {name: (kind, size)}."""
    types = {}
    for line in Path(path).read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) != 3:
            raise ValueError(f"malformed line: {line!r}")
        types[parts[0]] = (parts[1], int(parts[2]))
    return types


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--instance", default=DEFAULT_INSTANCE, help="IDA instance (port or name)")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--ports", default=os.environ.get("IDA_MCP_PORTS", "13337-13437"))
    parser.add_argument("--dry-run", action="store_true", help="report counts, write nothing")
    args = parser.parse_args()

    port, payload = collect(args.instance, args.ports)
    kept = sorted((row for row in payload if NAME_OK.match(row[0])), key=lambda row: row[0])
    print(f"instance {port}: {len(kept)} named types ({len(payload) - len(kept)} unnamed, skipped)")
    if args.dry_run:
        return
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(kept))
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
