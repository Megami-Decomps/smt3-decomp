#!/usr/bin/env python3
"""Export every named function prototype from the SLUS_209.11 IDB.

One line per function, `0xADDR name <C prototype>`, to config/smt3/ida_protos.txt.
The IDB's parameter names came with the HD symbol recovery, so this is where the
tree's parameter names are checked against. Read-only on the IDB side.
"""

import argparse
import base64
import json
import os
import sys
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ida_types import IDA_SCRIPTS, eval_in_ida, PAGE  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "config" / "smt3" / "ida_protos.txt"
DEFAULT_INSTANCE = "SLUS_209.11"
HEADER = "# generated by tools/ida_protos.py; do not edit. 0xADDR name prototype"

IDA_PAYLOAD = r'''
def export():
    import base64, json, zlib
    import idautils, ida_nalt, ida_name, ida_typeinf
    rows = []
    for ea in idautils.Functions():
        name = ida_name.get_name(ea)
        if not name or name.startswith(("sub_", "nullsub_", "j_", "loc_")):
            continue
        tif = ida_typeinf.tinfo_t()
        if not ida_nalt.get_tinfo(tif, ea):
            continue
        proto = ida_typeinf.print_tinfo("", 0, 0, ida_typeinf.PRTYPE_1LINE, tif, name, "")
        if not proto:
            continue
        rows.append([ea, name, proto])
    blob = json.dumps(rows, separators=(",", ":")).encode()
    return base64.b64encode(zlib.compress(blob, 9)).decode()


PROTO_BLOB = export()
len(PROTO_BLOB)
'''


def collect(instance, ports):
    sys.path.insert(0, str(IDA_SCRIPTS))
    import ida

    instances = ida.get_instances(ida.parse_ports(ports), refresh=False)
    port = ida.resolve_target(instance, instances)
    total = int(eval_in_ida(ida, port, IDA_PAYLOAD, True))
    pages = []
    for start in range(0, total, PAGE):
        page = eval_in_ida(ida, port, f"PROTO_BLOB[{start}:{start + PAGE}]", False)
        if len(page) != min(PAGE, total - start):
            raise SystemExit(f"short page at {start}: got {len(page)} characters")
        pages.append(page)
    return port, json.loads(zlib.decompress(base64.b64decode("".join(pages))))


def load(path=DEFAULT_OUTPUT):
    """{name: (addr, prototype)}"""
    out = {}
    for line in Path(path).read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        addr, name, proto = line.split(" ", 2)
        out[name] = (int(addr, 16), proto)
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--instance", default=DEFAULT_INSTANCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--ports", default=os.environ.get("IDA_MCP_PORTS", "13337-13437"))
    args = parser.parse_args()
    port, rows = collect(args.instance, args.ports)
    rows.sort()
    lines = [HEADER] + [f"0x{ea:08X} {name} {proto}" for ea, name, proto in rows]
    args.output.write_text("\n".join(lines) + "\n")
    print(f"instance {port}: {len(rows)} prototypes -> {args.output}")


if __name__ == "__main__":
    main()
